// Command math-assets materializes self-contained math CSS from locked assets.
package main

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	root := "assets/katex/0.19.1"
	css, err := os.ReadFile(filepath.Join(root, "katex.min.css"))
	if err != nil {
		return err
	}
	pattern := regexp.MustCompile(`src:url\(fonts/([^)]*\.woff2)\)[^}]*`)
	var failed error
	css = pattern.ReplaceAllFunc(css, func(match []byte) []byte {
		name := pattern.FindSubmatch(match)[1]
		font, err := os.ReadFile(filepath.Join(root, "fonts", string(name)))
		if err != nil {
			failed = err
			return nil
		}
		return []byte(`src:url(data:font/woff2;base64,` + base64.StdEncoding.EncodeToString(font) + `) format("woff2")`)
	})
	if failed != nil {
		return failed
	}
	if bytes.Contains(css, []byte("url(fonts/")) {
		return fmt.Errorf("unresolved math font URL")
	}
	css = append([]byte("/* Generated by go generate from Muamba-locked KaTeX 0.19.1; MIT license in katex/0.19.1/LICENSE. */\n"), css...)
	css = append(css, []byte(`
.margo-math--inline{display:inline}.margo-math--display{display:block;max-width:100%;overflow-x:auto;margin-block:1.25em;padding-block:.15em}.margo-math__source{white-space:pre-wrap;font-family:monospace;overflow-wrap:anywhere}.margo-math__error{display:block;font-size:.85em;color:#b91c1c;overflow-wrap:anywhere}.margo-math [hidden]{display:none!important}.margo-math__output>.katex{color:inherit}.margo-math:focus-visible{outline:2px solid currentColor;outline-offset:3px}.margo-math .katex-display{margin:0;min-inline-size:max-content}.margo-math--display .katex-html{white-space:nowrap}.margo-math math{font-size:inherit}
.dark .margo-math__error{color:#fca5a5}
@media print{.margo-math--display{overflow:visible;break-inside:avoid}.margo-math__output{overflow:visible}}
.margo-deck .margo-math--display{overflow:visible}
`)...)
	return os.WriteFile("assets/math.css", css, 0644)
}
